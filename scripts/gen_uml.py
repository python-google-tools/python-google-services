#!/usr/bin/env python
"""Generate UML class/package diagrams from the googlepy package.

Runs ``pyreverse`` (from pylint) with Mermaid output and wraps the result in a
fenced ``mermaid`` block that Material for MkDocs renders natively. The output
files are included by ``docs/architecture.md`` via pymdownx snippets, so the
diagrams always mirror the actual source.

Usage::

    python scripts/gen_uml.py
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGE = REPO_ROOT / "src" / "googlepy"
DIAGRAMS_DIR = REPO_ROOT / "docs" / "diagrams"

HEADER = "<!-- Auto-generated by scripts/gen_uml.py — do not edit by hand. -->\n"


def _wrap_mermaid(mmd: str) -> str:
    return f"{HEADER}```mermaid\n{mmd.strip()}\n```\n"


def generate() -> None:
    DIAGRAMS_DIR.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        cmd = [
            sys.executable,
            "-m",
            "pylint.pyreverse.main",
            "-o",
            "mmd",
            "-p",
            "googlepy",
            "-d",
            str(tmp_path),
            str(PACKAGE),
        ]
        # pyreverse's module entry point differs across pylint versions; fall
        # back to the console script if the module path is unavailable.
        try:
            subprocess.run(cmd, check=True, cwd=REPO_ROOT)
        except (subprocess.CalledProcessError, ModuleNotFoundError):
            subprocess.run(
                ["pyreverse", "-o", "mmd", "-p", "googlepy", "-d", str(tmp_path), str(PACKAGE)],
                check=True,
                cwd=REPO_ROOT,
            )

        for kind, out_name in (("classes", "classes.md"), ("packages", "packages.md")):
            src = tmp_path / f"{kind}_googlepy.mmd"
            if src.is_file():
                (DIAGRAMS_DIR / out_name).write_text(
                    _wrap_mermaid(src.read_text(encoding="utf-8")), encoding="utf-8"
                )
                print(f"wrote {DIAGRAMS_DIR / out_name}")


if __name__ == "__main__":
    generate()
